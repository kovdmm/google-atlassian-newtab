const LANG_NAMES = { en: "English", ru: "Русский", uk: "Українська", de: "Deutsch" };

// Chrome UI language when it is supported, English otherwise
function browserLang() {
  const code = (chrome.i18n?.getUILanguage?.() || navigator.language || "en").slice(0, 2).toLowerCase();
  return I18N[code] ? code : "en";
}

let lang = browserLang();

// t("projectKeyHint", url) – {0}, {1}… are replaced with the arguments
const t = (key, ...args) => (I18N[lang][key] ?? I18N.en[key] ?? key).replace(/\{(\d)\}/g, (_, i) => args[i] ?? "");

// data-i18n → text, data-i18n-ph → placeholder, data-i18n-title → title and aria-label
function applyI18n(root = document) {
  document.documentElement.lang = lang;
  root.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-ph]").forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll("[data-i18n-title]").forEach(el => {
    el.title = t(el.dataset.i18nTitle);
    el.setAttribute("aria-label", el.title);
  });
}
